import type { ReactNode } from "react";
import { motion } from "motion/react";
import { Cpu, RefreshCw, Sparkles, TriangleAlert } from "lucide-react";
import type { ArtifactSource } from "@/data/models";
import { useAiStatus } from "@/services/ai";
import { Button } from "@/components/ui/Button";
import { Badge, Skeleton } from "@/components/ui/primitives";
import { cancelJob, clearJobError, useJob } from "./jobs";

export function SourceBadge({ source, truncated }: { source: ArtifactSource; truncated?: boolean }) {
  return (
    <span className="flex flex-wrap items-center gap-1.5">
      {source === "ai" ? (
        <Badge tone="accent">
          <Sparkles className="h-3 w-3" /> Generated by Recall AI
        </Badge>
      ) : (
        <Badge tone="neutral" title="Extracted from your document on this device, without AI">
          <Cpu className="h-3 w-3" /> Basic mode · extracted, not AI
        </Badge>
      )}
      {truncated && <Badge tone="warning">Long document — AI read the first part only</Badge>}
    </span>
  );
}

/** Lets the student choose Recall AI (if connected) or offline basic mode. */
export function GenerateChoice({
  title,
  description,
  icon,
  onGenerate,
  jobKey,
  children,
}: {
  title: string;
  description: string;
  icon: ReactNode;
  onGenerate: (source: ArtifactSource) => void;
  jobKey: string;
  children?: ReactNode;
}) {
  const ai = useAiStatus();
  const job = useJob(jobKey);
  if (job.running) return <GeneratingState jobKey={jobKey} label={title} />;
  return (
    <motion.div initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} className="flex flex-col items-center rounded-3xl border border-dashed border-border-strong px-6 py-12 text-center">
      <span className="grid h-12 w-12 place-items-center rounded-2xl bg-accent-soft text-accent-text">{icon}</span>
      <h3 className="mt-4 text-base font-semibold">{title}</h3>
      <p className="mt-1.5 max-w-md text-sm leading-relaxed text-muted">{description}</p>
      {children && <div className="mt-5 w-full max-w-md text-left">{children}</div>}
      {job.error && (
        <p role="alert" className="mt-4 flex max-w-md items-start gap-2 rounded-xl bg-danger-soft px-3 py-2.5 text-left text-sm text-danger">
          <TriangleAlert className="mt-0.5 h-4 w-4 shrink-0" />
          <span className="flex-1">{job.error}</span>
          <button type="button" className="text-xs font-semibold underline" onClick={() => clearJobError(jobKey)}>
            Dismiss
          </button>
        </p>
      )}
      <div className="mt-6 flex w-full max-w-sm flex-col gap-2 sm:flex-row sm:justify-center">
        {ai?.configured && (
          <Button onClick={() => onGenerate("ai")} icon={<Sparkles className="h-4 w-4" />}>
            Generate with Recall AI
          </Button>
        )}
        <Button variant={ai?.configured ? "secondary" : "primary"} onClick={() => onGenerate("local")} icon={<Cpu className="h-4 w-4" />}>
          {ai?.configured ? "Basic mode" : "Generate in basic mode"}
        </Button>
      </div>
      {ai && !ai.configured && <p className="mt-3 max-w-sm text-xs leading-relaxed text-subtle">Recall AI isn't connected, so this uses basic mode: it extracts sentences and definitions from your document on this device. Connect AI for written explanations.</p>}
    </motion.div>
  );
}

export function GeneratingState({ jobKey, label }: { jobKey: string; label: string }) {
  return (
    <div className="rounded-3xl border border-border bg-surface p-6" role="status" aria-live="polite">
      <div className="flex items-center justify-between gap-3">
        <div className="flex items-center gap-3">
          <span className="relative grid h-10 w-10 place-items-center rounded-xl bg-accent-soft text-accent-text">
            <Sparkles className="h-5 w-5" />
            <motion.span className="absolute inset-0 rounded-xl ring-2 ring-accent" animate={{ opacity: [0.6, 0, 0.6], scale: [1, 1.15, 1] }} transition={{ duration: 1.8, repeat: Infinity }} />
          </span>
          <div>
            <p className="text-sm font-semibold">{label}…</p>
            <p className="text-xs text-subtle">Reading your document. Large PDFs can take a minute — you can switch tabs.</p>
          </div>
        </div>
        <Button variant="ghost" size="sm" onClick={() => cancelJob(jobKey)}>
          Cancel
        </Button>
      </div>
      <div className="mt-6 space-y-3">
        <Skeleton className="h-4 w-2/3" />
        <Skeleton className="h-4 w-full" />
        <Skeleton className="h-4 w-5/6" />
        <Skeleton className="h-4 w-3/4" />
      </div>
    </div>
  );
}

export function ArtifactHeader({ source, truncated, onRegenerate, jobKey, actions }: { source: ArtifactSource; truncated?: boolean; onRegenerate: (source: ArtifactSource) => void; jobKey: string; actions?: ReactNode }) {
  const ai = useAiStatus();
  const job = useJob(jobKey);
  return (
    <div className="mb-5 flex flex-wrap items-center justify-between gap-3">
      <SourceBadge source={source} truncated={truncated} />
      <div className="flex items-center gap-1">
        {actions}
        {ai?.configured && source === "local" ? (
          <Button size="sm" variant="soft" onClick={() => onRegenerate("ai")} loading={job.running} icon={<Sparkles className="h-3.5 w-3.5" />}>
            Upgrade with AI
          </Button>
        ) : (
          <Button size="sm" variant="ghost" onClick={() => onRegenerate(source)} loading={job.running} icon={<RefreshCw className="h-3.5 w-3.5" />}>
            Regenerate
          </Button>
        )}
      </div>
    </div>
  );
}
