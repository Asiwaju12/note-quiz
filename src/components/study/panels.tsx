export function useArtifact<K extends ArtifactKind>(docId: string, kind: K): Artifact<K> | undefined {
  const artifacts = useCollection<Artifact>("artifacts");
  return artifacts.find((a) => a.id === `${docId}:${kind}`) as Artifact<K> | undefined;
}

export function startArtifact(doc: StudyDocument, kind: ArtifactKind, source: ArtifactSource) {
  const labels = { summary: "Summary", notes: "Study notes", keyTerms: "Key terms", guide: "Study guide" };
  void runJob(`${doc.id}:${kind}`, (signal) => generateArtifact(doc, kind, source, signal)).then((result) => {
    if (result) toast(`${labels[kind]} ready`, { description: source === "ai" ? "Generated by Recall AI" : "Basic mode (extracted from your document)" });
  });
}

/* ───────────── Overview ───────────── */

export function OverviewPanel({ doc, onTab }: { doc: StudyDocument; onTab: (tab: string) => void }) {
  const guide = useArtifact(doc.id, "guide");
  const summary = useArtifact(doc.id, "summary");
  const topicProgress = useCollection<TopicProgress>("topicProgress").filter((t) => t.docId === doc.id);
  const decks = useCollection<SavedDeck>("decks");
  const deck = decks.find((d) => d.docId === doc.id && d.kind === "document");
  const cards = useCollection<Flashcard>("cards").filter((c) => c.deckId === deck?.id);
  const attempts = useCollection<Attempt>("attempts").filter((a) => a.docId === doc.id);
  const answered = attempts.reduce((sum, a) => sum + a.answers.length, 0);
  const correct = attempts.reduce((sum, a) => sum + a.answers.filter((x) => x.correct).length, 0);
  const reviewed = cards.filter((c) => c.srs.reps > 0).length;
  const topics = guide?.data.topics ?? [];
  const done = topics.filter((t) => topicProgress.some((p) => p.topicId === t.id)).length;
  const remaining = topics.filter((t) => !topicProgress.some((p) => p.topicId === t.id));

  const tools = [
    { tab: "summary", label: "Summary", icon: FileText, ready: Boolean(summary) },
    { tab: "notes", label: "Study notes", icon: NotebookText, ready: false },
    { tab: "flashcards", label: "Flashcards", icon: Layers, ready: cards.length > 0 },
    { tab: "practice", label: "Practice", icon: Target, ready: false },
    { tab: "terms", label: "Key terms", icon: BookMarked, ready: false },
    { tab: "guide", label: "Study guide", icon: MapIcon, ready: topics.length > 0 },
  ];

  return (
    <div className="space-y-5">
      <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <StatTile label="Topics completed" value={topics.length ? `${done}/${topics.length}` : "—"} sub={topics.length ? `${remaining.length} remaining` : "Create a study guide"} />
        <StatTile label="Flashcards reviewed" value={cards.length ? `${reviewed}/${cards.length}` : "—"} sub={cards.length ? undefined : "No cards yet"} />
        <StatTile label="Questions answered" value={answered || "—"} sub={answered ? `${attempts.length} session${attempts.length === 1 ? "" : "s"}` : "Try a practice quiz"} />
        <StatTile label="Accuracy" value={answered ? `${Math.round((correct / answered) * 100)}%` : "—"} sub={answered ? `${correct} correct` : undefined} />
      </div>

      {summary && (
        <Card className="p-5">
          <div className="mb-2 flex items-center justify-between">
            <p className="text-sm font-semibold">In short</p>
            <button type="button" onClick={() => onTab("summary")} className="text-xs font-medium text-accent-text hover:underline">
              Full summary
            </button>
          </div>
          <p className="text-[15px] leading-relaxed text-muted">{summary.data.short}</p>
        </Card>
      )}

      {remaining.length > 0 && (
        <Card className="p-5">
          <div className="mb-3 flex items-center justify-between">
            <p className="text-sm font-semibold">Up next in your study guide</p>
            <span className="text-xs text-subtle">{Math.round((done / topics.length) * 100)}% complete</span>
          </div>
          <ProgressBar value={done / topics.length} className="mb-4" />
          <button type="button" onClick={() => onTab("guide")} className="flex w-full items-center gap-3 rounded-xl bg-surface-2 p-3 text-left hover:bg-surface-3">
            <Circle className="h-5 w-5 text-border-strong" />
            <span className="min-w-0 flex-1">
              <span className="block truncate text-sm font-medium">{remaining[0].title}</span>
              <span className="text-xs text-subtle">~{formatMinutes(remaining[0].estimatedMinutes)}</span>
            </span>
          </button>
        </Card>
      )}

      <div>
        <p className="mb-3 text-sm font-semibold">Study tools</p>
        <div className="grid grid-cols-2 gap-2 sm:grid-cols-3">
          {tools.map((tool) => (
            <button key={tool.tab} type="button" onClick={() => onTab(tool.tab)} className="card card-interactive flex items-center gap-3 p-3.5 text-left">
              <span className="grid h-9 w-9 shrink-0 place-items-center rounded-xl bg-accent-soft text-accent-text">
                <tool.icon className="h-[18px] w-[18px]" />
              </span>
              <span className="min-w-0 truncate text-sm font-medium">{tool.label}</span>
              {tool.ready && <CheckCircle2 className="ml-auto h-4 w-4 shrink-0 text-success" />}
            </button>
          ))}
        </div>
      </div>
      {doc.charCount < 100 && <p className="rounded-2xl bg-warning-soft p-4 text-sm text-warning">This PDF has no selectable text (it may be scanned). You can still read it, but summaries, flashcards and AI answers need text. Run it through OCR and upload again.</p>}
    </div>
  );
}

/* ───────────── Summary ───────────── */

function ListBlock({ title, items }: { title: string; items: string[] }) {
  if (!items.length) return null;
  return (
    <Card className="p-5">
      <p className="mb-3 text-sm font-semibold">{title}</p>
      <ul className="space-y-2">
        {items.map((item, index) => (
          <li key={index} className="flex gap-2.5 text-[15px] leading-relaxed">
            <span className="mt-2.5 h-1.5 w-1.5 shrink-0 rounded-full bg-accent" />
            {item}
          </li>
        ))}
      </ul>
    </Card>
  );
}

export function SummaryPanel({ doc, onPage }: { doc: StudyDocument; onPage: (page: number) => void }) {
  const artifact = useArtifact(doc.id, "summary");
  const job = useJob(`${doc.id}:summary`);
  const [length, setLength] = useState<"short" | "detailed">("short");
  if (!artifact) return <GenerateChoice jobKey={`${doc.id}:summary`} title="Create a smart summary" description="Get a short overview, a detailed summary, the main ideas, key concepts, definitions and takeaways." icon={<FileText className="h-6 w-6" />} onGenerate={(source) => startArtifact(doc, "summary", source)} />;
  if (job.running) return <GeneratingState jobKey={`${doc.id}:summary`} label="Updating summary" />;
  const data: SummaryData = artifact.data;
  return (
    <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }}>
      <ArtifactHeader source={artifact.source} truncated={artifact.truncated} jobKey={`${doc.id}:summary`} onRegenerate={(source) => startArtifact(doc, "summary", source)} />
      <div className="space-y-4">
        <Card className="p-5 sm:p-6">
          <div className="mb-4 flex items-center justify-between gap-3">
            <p className="text-sm font-semibold">Summary</p>
            <Chips label="Summary length" value={length} onChange={(v) => setLength(v as "short" | "detailed")} options={[{ value: "short", label: "Short" }, { value: "detailed", label: "Detailed" }]} />
          </div>
          {length === "short" ? <p className="text-[15px] leading-relaxed">{data.short}</p> : <Markdown text={data.detailed} onPage={onPage} />}
        </Card>
        <div className="grid gap-4 lg:grid-cols-2">
          <ListBlock title="Main ideas" items={data.mainIdeas} />
          <ListBlock title="Key takeaways" items={data.takeaways} />
        </div>
        {data.keyConcepts.length > 0 && (
          <Card className="p-5">
            <p className="mb-3 text-sm font-semibold">Important concepts</p>
            <div className="flex flex-wrap gap-2">
              {data.keyConcepts.map((concept) => (
                <Badge key={concept} tone="accent" className="px-3 py-1 text-[13px]">
                  {concept}
                </Badge>
              ))}
            </div>
          </Card>
        )}
        {data.definitions.length > 0 && (
          <Card className="divide-y divide-border">
            <p className="px-5 py-4 text-sm font-semibold">Key definitions</p>
            {data.definitions.map((def) => (
              <div key={def.term} className="px-5 py-3.5">
                <p className="flex items-center justify-between gap-2 text-sm font-semibold">
                  {def.term}
                  {def.page ? (
                    <button type="button" onClick={() => onPage(def.page!)} className="font-mono text-[11px] font-normal text-accent-text hover:underline">
                      p. {def.page}
                    </button>
                  ) : null}
                </p>
                <p className="mt-1 text-sm leading-relaxed text-muted">{def.definition}</p>
              </div>
            ))}
          </Card>
        )}
      </div>
    </motion.div>
  );
}

/* ───────────── Notes ───────────── */

export function NotesPanel({ doc, onPage }: { doc: StudyDocument; onPage: (page: number) => void }) {
  const artifact = useArtifact(doc.id, "notes");
  const job = useJob(`${doc.id}:notes`);
  if (!artifact) return <GenerateChoice jobKey={`${doc.id}:notes`} title="Generate revision notes" description="Structured notes with headings, definitions, explanations, examples and key points — with page references." icon={<NotebookText className="h-6 w-6" />} onGenerate={(source) => startArtifact(doc, "notes", source)} />;
  if (job.running) return <GeneratingState jobKey={`${doc.id}:notes`} label="Updating notes" />;
  const data: NotesData = artifact.data;
  return (
    <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }}>
      <ArtifactHeader
        source={artifact.source}
        truncated={artifact.truncated}
        jobKey={`${doc.id}:notes`}
        onRegenerate={(source) => startArtifact(doc, "notes", source)}
        actions={
          <Button
            size="sm"
            variant="ghost"
            icon={<Copy className="h-3.5 w-3.5" />}
            onClick={async () => {
              try {
                await navigator.clipboard.writeText(data.markdown);
                toast("Notes copied as Markdown");
              } catch {
                toast("Couldn't copy", { tone: "error" });
              }
            }}
          >
            Copy
          </Button>
        }
      />
      <Card className="p-5 sm:p-8">
        <Markdown text={data.markdown} onPage={onPage} />
      </Card>
    </motion.div>
  );
}

/* ───────────── Key terms ───────────── */

export function KeyTermsPanel({ doc, onPage }: { doc: StudyDocument; onPage: (page: number) => void }) {
  const artifact = useArtifact(doc.id, "keyTerms");
  const job = useJob(`${doc.id}:keyTerms`);
  const [query, setQuery] = useState("");
  if (!artifact) return <GenerateChoice jobKey={`${doc.id}:keyTerms`} title="Extract key terms" description="Important terms with simple definitions and examples, linked to the page they appear on." icon={<BookMarked className="h-6 w-6" />} onGenerate={(source) => startArtifact(doc, "keyTerms", source)} />;
  if (job.running) return <GeneratingState jobKey={`${doc.id}:keyTerms`} label="Updating key terms" />;
  const data: KeyTermsData = artifact.data;
  const terms = data.terms.filter((t) => !query || `${t.term} ${t.definition}`.toLowerCase().includes(query.toLowerCase()));
  return (
    <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }}>
      <ArtifactHeader
        source={artifact.source}
        jobKey={`${doc.id}:keyTerms`}
        onRegenerate={(source) => startArtifact(doc, "keyTerms", source)}
        actions={
          <Button
            size="sm"
            variant="ghost"
            icon={<Layers className="h-3.5 w-3.5" />}
            onClick={() => {
              const target = getOrCreateDocDeck(doc);
              const made = createCards(target.id, data.terms.map((t) => ({ front: t.term, back: t.definition, sourcePage: t.page, docId: doc.id })));
              toast(`${made.length} flashcards added`, { description: "Find them in the Flashcards tab." });
            }}
          >
            Make flashcards
          </Button>
        }
      />
      {data.terms.length > 8 && <input value={query} onChange={(e) => setQuery(e.target.value)} placeholder="Filter terms" aria-label="Filter terms" className="mb-4 h-10 w-full rounded-xl border border-border bg-surface px-3.5 text-sm focus:border-accent focus:outline-none sm:max-w-xs" />}
      <div className="grid gap-3 md:grid-cols-2">
        {terms.map((term, index) => (
          <motion.div key={term.term} initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: Math.min(index, 12) * 0.03 }}>
            <Card className="h-full p-5">
              <div className="flex items-start justify-between gap-2">
                <h3 className="font-semibold">{term.term}</h3>
                {term.page ? (
                  <button type="button" onClick={() => onPage(term.page!)} className="shrink-0 font-mono text-[11px] text-accent-text hover:underline">
                    p. {term.page}
                  </button>
                ) : null}
              </div>
              <p className="mt-1.5 text-sm leading-relaxed text-muted">{term.definition}</p>
              {term.example && (
                <p className="mt-3 rounded-xl bg-surface-2 p-3 text-[13px] leading-relaxed">
                  <span className="font-medium text-accent-text">Example · </span>
                  {term.example}
                </p>
              )}
            </Card>
          </motion.div>
        ))}
      </div>
    </motion.div>
  );
}

/* ───────────── Study guide ───────────── */

export function GuidePanel({ doc, onPage, onPractiseTopic }: { doc: StudyDocument; onPage: (page: number) => void; onPractiseTopic: (topic: string, pages: number[]) => void }) {
  const artifact = useArtifact(doc.id, "guide");
  const job = useJob(`${doc.id}:guide`);
  const progress = useCollection<TopicProgress>("topicProgress").filter((p) => p.docId === doc.id);
  if (!artifact) return <GenerateChoice jobKey={`${doc.id}:guide`} title="Build a study guide" description="Break the document into manageable topics in a logical order, with time estimates and learning objectives." icon={<MapIcon className="h-6 w-6" />} onGenerate={(source) => startArtifact(doc, "guide", source)} />;
  if (job.running) return <GeneratingState jobKey={`${doc.id}:guide`} label="Updating study guide" />;
  const data: GuideData = artifact.data;
  const done = data.topics.filter((t) => progress.some((p) => p.topicId === t.id)).length;
  const totalMinutes = data.topics.reduce((sum, t) => sum + t.estimatedMinutes, 0);
  return (
    <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }}>
      <ArtifactHeader source={artifact.source} truncated={artifact.truncated} jobKey={`${doc.id}:guide`} onRegenerate={(source) => startArtifact(doc, "guide", source)} />
      <Card className="mb-4 p-5">
        <div className="flex items-baseline justify-between">
          <p className="text-sm font-semibold">
            {done} of {data.topics.length} topics complete
          </p>
          <p className="text-xs text-subtle">~{formatMinutes(totalMinutes)} total</p>
        </div>
        <ProgressBar value={data.topics.length ? done / data.topics.length : 0} className="mt-3" />
      </Card>
      <ol className="relative space-y-3">
        {data.topics.map((topic, index) => {
          const complete = progress.some((p) => p.topicId === topic.id);
          const next = !complete && data.topics.slice(0, index).every((t) => progress.some((p) => p.topicId === t.id));
          return (
            <li key={topic.id}>
              <Card className={cn("p-5 transition-colors", next && "border-accent/50 ring-4 ring-[var(--ring)]/10")}>
                <div className="flex items-start gap-3">
                  <button type="button" onClick={() => completeTopic(doc.id, topic.id, topic.title)} aria-label={complete ? `Mark “${topic.title}” as not done` : `Mark “${topic.title}” as complete`} aria-pressed={complete} className="mt-0.5 shrink-0">
                    {complete ? (
                      <motion.span initial={{ scale: 0.5 }} animate={{ scale: 1 }} className="block">
                        <CheckCircle2 className="h-6 w-6 text-success" />
                      </motion.span>
                    ) : (
                      <Circle className="h-6 w-6 text-border-strong hover:text-accent" />
                    )}
                  </button>
                  <div className="min-w-0 flex-1">
                    <div className="flex flex-wrap items-center gap-2">
                      <span className="text-xs text-subtle">Topic {index + 1}</span>
                      {next && <Badge tone="accent">Up next</Badge>}
                    </div>
                    <h3 className={cn("mt-0.5 font-semibold leading-snug", complete && "text-muted")}>{topic.title}</h3>
                    {topic.summary && <p className="mt-1 text-sm leading-relaxed text-muted">{topic.summary}</p>}
                    {topic.objectives.length > 0 && (
                      <ul className="mt-3 space-y-1">
                        {topic.objectives.map((objective) => (
                          <li key={objective} className="flex gap-2 text-[13px] text-muted">
                            <ListChecks className="mt-0.5 h-3.5 w-3.5 shrink-0 text-accent-text" />
                            {objective}
                          </li>
                        ))}
                      </ul>
                    )}
                    <div className="mt-4 flex flex-wrap items-center gap-2">
                      <Badge tone="neutral">~{formatMinutes(topic.estimatedMinutes)}</Badge>
                      {topic.pages.length > 0 && (
                        <button type="button" onClick={() => onPage(topic.pages[0])} className="rounded-full bg-accent-soft px-2.5 py-0.5 text-[11px] font-medium text-accent-text hover:underline">
                          {topic.pages.length === 1 ? `Read p. ${topic.pages[0]}` : `Read pp. ${topic.pages[0]}–${topic.pages[topic.pages.length - 1]}`}
                        </button>
                      )}
                      <Button size="sm" variant="ghost" onClick={() => onPractiseTopic(topic.title, topic.pages)} icon={<Target className="h-3.5 w-3.5" />} className="ml-auto">
                        Practise
                      </Button>
                    </div>
                  </div>
                </div>
              </Card>
            </li>
          );
        })}
      </ol>
    </motion.div>
  );
}

/* ───────────── Flashcards ───────────── */

export function FlashcardsPanel({ doc }: { doc: StudyDocument }) {
  const decks = useCollection<SavedDeck>("decks");
  const allCards = useCollection<Flashcard>("cards");
  const deck = decks.find((d) => d.docId === doc.id && d.kind === "document");
  const cards = useMemo(() => allCards.filter((c) => deck && c.deckId === deck.id), [allCards, deck]);
  const jobKey = `${doc.id}:flashcards`;
  const job = useJob(jobKey);
  const [count, setCount] = useState(20);
  const generate = (source: ArtifactSource) => {
    void runJob(jobKey, async (signal) => {
      const generated = await generateCards(doc, count, source, signal);
      const target = getOrCreateDocDeck(doc);
      const made = createCards(target.id, generated.map((c) => ({ front: c.front, back: c.back, topic: c.topic, sourcePage: c.page || undefined, docId: doc.id })));
      toast(`${made.length} flashcards created`, { description: source === "ai" ? "Generated by Recall AI" : "Basic mode (from definitions in your document)" });
      return made;
    });
  };
  if (job.running) return <GeneratingState jobKey={jobKey} label="Creating flashcards" />;
  if (!cards.length) {
    return (
      <GenerateChoice jobKey={jobKey} title="Generate flashcards" description="Question-and-answer cards from this document. Edit, add your own, and review them with spaced repetition." icon={<Layers className="h-6 w-6" />} onGenerate={generate}>
        <p className="mb-2 text-center text-[13px] font-medium">How many cards?</p>
        <Chips label="Number of cards" className="justify-center" value={count} onChange={(v) => setCount(v as number)} options={[10, 20, 30, 40].map((v) => ({ value: v, label: String(v) }))} />
      </GenerateChoice>
    );
  }
  return (
    <div>
      <div className="mb-4 flex items-center justify-between gap-2">
        <p className="text-sm text-muted">{cards.length} cards in this document's collection</p>
        <GenerateMore onGenerate={generate} />
      </div>
      <CardManager deckId={deck!.id} cards={cards} docId={doc.id} title={doc.title} />
    </div>
  );
}

function GenerateMore({ onGenerate }: { onGenerate: (source: ArtifactSource) => void }) {
  const ai = useAiStatus();
  return (
    <Button size="sm" variant="soft" icon={<Sparkles className="h-3.5 w-3.5" />} onClick={() => onGenerate(ai?.configured ? "ai" : "local")}>
      {ai?.configured ? "Generate more" : "Generate more (basic)"}
    </Button>
  );
}

/* ───────────── Practice-question history for a document ───────────── */

export function PracticeHistory({ docId }: { docId: string }) {
  const attempts = useCollection<Attempt>("attempts")
    .filter((a) => a.docId === docId)
    .sort((a, b) => b.finishedAt.localeCompare(a.finishedAt))
    .slice(0, 5);
  if (!attempts.length) return null;
  return (
    <Card className="mt-6 divide-y divide-border">
      <p className="flex items-center gap-2 px-5 py-3.5 text-sm font-semibold">
        <ClipboardList className="h-4 w-4 text-subtle" /> Recent sessions
      </p>
      {attempts.map((attempt) => (
        <div key={attempt.id} className="flex items-center justify-between px-5 py-3 text-sm">
          <span className="min-w-0 truncate">
            {attempt.mode === "exam" ? "Exam" : "Practice"} · {new Date(attempt.finishedAt).toLocaleDateString(undefined, { month: "short", day: "numeric" })}
          </span>
          <span className={cn("tabular font-medium", attempt.scorePct >= 80 ? "text-success" : attempt.scorePct >= 60 ? "text-warning" : "text-danger")}>
            {attempt.correct}/{attempt.total} · {attempt.scorePct}%
          </span>
        </div>
      ))}
      <Link to="/progress" className="block px-5 py-3 text-center text-xs font-medium text-accent-text hover:underline">
        See all progress
      </Link>
    </Card>
  );
}
